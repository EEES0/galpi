let recognitionStatus = "start";

function t(key) {
    const language = userLanguageSelect.value.split("-")[0];
    return translations[language]?.[key] || translations.ko[key] || key;
}

function setRecognitionStatus(key) {
    recognitionStatus = key;
    statusElement.textContent = t(key);
    startBtn.setAttribute("aria-label", t(startBtn.getAttribute("aria-pressed") === "true" ? "stop" : "start"));
}

function applyTranslations() {
    document.documentElement.lang = userLanguageSelect.value;
    document.querySelectorAll("[data-i18n]").forEach(element => {
        element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(element => {
        element.setAttribute("aria-label", t(element.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(element => {
        element.setAttribute("title", t(element.dataset.i18nTitle));
    });
    editTranscriptButton.dataset.i18n = transcriptEditing ? "finishEditing" : "editTranscript";
    editTranscriptButton.textContent = t(editTranscriptButton.dataset.i18n);
    finalElement.querySelectorAll(".segment").forEach(configureTranscriptEditor);
    renderPageList();
    setRecognitionStatus(recognitionStatus);
}
